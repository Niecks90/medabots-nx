#!/usr/bin/env python3
"""
Extract map and ELF symbols from the Medabots Rokusho build.
Generates:
  - symbols/imported_symbols.tsv
  - symbols/imported_data_symbols.tsv
  - game.toml
  - switch/medabots_symbols.h
"""

import sys
import os
import re
import hashlib
import subprocess
from pathlib import Path

def main():
    root_dir = Path(__file__).resolve().parents[1]
    decomp_dir = root_dir / "decomp"
    map_path = decomp_dir / "medabots_rokusho.map"
    elf_path = decomp_dir / "medabots_rokusho.elf"
    rom_path = decomp_dir / "medabots_rokusho.gba"

    if not map_path.exists() or not elf_path.exists() or not rom_path.exists():
        print(f"Error: Missing build artifacts in {decomp_dir}", file=sys.stderr)
        print("Run 'make -C decomp' first.", file=sys.stderr)
        sys.exit(1)

    print(f"[extract_map_symbols] Reading {map_path}...")
    with open(map_path, "r", encoding="utf-8", errors="replace") as f:
        map_text = f.read()

    # 1. Extract gLanguage address
    m = re.search(r'^\s*(0x[0-9a-fA-F]+)\s+gLanguage\b', map_text, re.MULTILINE)
    if not m:
        m = re.search(r'\bgLanguage\s*=\s*(0x[0-9a-fA-F]+)', map_text)
    if not m:
        print("Warning: gLanguage not found in map, defaulting to 0x02000000", file=sys.stderr)
        lang_addr = 0x02000000
    else:
        lang_addr = int(m.group(1), 16)

    print(f"[extract_map_symbols] Found gLanguage at {lang_addr:#010x}")

    # Write switch/medabots_symbols.h
    switch_symbols_path = root_dir / "switch" / "medabots_symbols.h"
    switch_symbols_path.parent.mkdir(parents=True, exist_ok=True)
    with open(switch_symbols_path, "w", encoding="utf-8") as f:
        f.write("#pragma once\n\n")
        f.write("#include <cstdint>\n\n")
        f.write("// Auto-generated by tools/extract_map_symbols.py. DO NOT EDIT.\n")
        f.write(f"constexpr uint32_t kMedabotsLanguageAddr = {lang_addr:#010x};\n")
    print(f"[extract_map_symbols] Wrote {switch_symbols_path}")

    # 2. Extract function symbols from ELF via readelf
    readelf_candidates = [
        "/opt/devkitpro/devkitARM/bin/arm-none-eabi-readelf",
        "arm-none-eabi-readelf",
        "readelf",
    ]
    readelf_bin = None
    for cand in readelf_candidates:
        if os.path.exists(cand) or subprocess.call(["which", cand], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL) == 0:
            readelf_bin = cand
            break

    funcs = {}  # addr -> (mode, name)
    data_syms = {}  # addr -> (region, size, name)

    if readelf_bin:
        print(f"[extract_map_symbols] Using readelf: {readelf_bin}")
        output = subprocess.check_output([readelf_bin, "-s", "-W", str(elf_path)], text=True)
        for line in output.splitlines():
            parts = line.strip().split()
            if len(parts) >= 8 and parts[0].endswith(":"):
                try:
                    val = int(parts[1], 16)
                    size = int(parts[2], 16) if parts[2].startswith("0x") else int(parts[2])
                    st_type = parts[3]
                    name = parts[7]
                except (ValueError, IndexError):
                    continue

                if name.startswith("$") or name.startswith(".") or name.startswith("_"):
                    continue

                addr = val & ~1
                is_thumb = (val & 1) != 0

                if st_type == "FUNC":
                    if 0x08000000 <= addr <= 0x09FFFFFF:
                        mode = "thumb" if is_thumb else "arm"
                        funcs[addr] = (mode, name)
                elif st_type == "OBJECT":
                    if 0x02000000 <= addr <= 0x0203FFFF:
                        data_syms[addr] = ("ewram", size, name)
                    elif 0x03000000 <= addr <= 0x03007FFF:
                        data_syms[addr] = ("iwram", size, name)
                    elif 0x08000000 <= addr <= 0x09FFFFFF:
                        data_syms[addr] = ("rom", size, name)

    # Supplement functions and data from map file
    for m in re.finditer(r'^\s*(0x08[0-9a-fA-F]{6})\s+(\w+)\s*$', map_text, re.MULTILINE):
        addr = int(m.group(1), 16)
        name = m.group(2)
        if name.startswith("$") or name.startswith(".") or name.startswith("_"):
            continue
        if addr not in funcs:
            mode = "arm" if addr < 0x0800025C else "thumb"
            funcs[addr] = (mode, name)

    # Absolute symbols from map file (EWRAM & IWRAM)
    for m in re.finditer(r'^\s*(0x[0-9a-fA-F]+)\s+(\w+)\s*=\s*(0x[0-9a-fA-F]+)', map_text, re.MULTILINE):
        addr = int(m.group(1), 16)
        name = m.group(2)
        if name.startswith("$") or name.startswith(".") or name.startswith("_"):
            continue
        if 0x02000000 <= addr <= 0x0203FFFF:
            data_syms[addr] = ("ewram", 0, name)
        elif 0x03000000 <= addr <= 0x03007FFF:
            data_syms[addr] = ("iwram", 0, name)

    # Write symbols/imported_symbols.tsv
    symbols_dir = root_dir / "symbols"
    symbols_dir.mkdir(parents=True, exist_ok=True)
    imported_symbols_path = symbols_dir / "imported_symbols.tsv"
    with open(imported_symbols_path, "w", encoding="utf-8") as f:
        f.write("# addr\tmode\tname\n")
        for addr in sorted(funcs.keys()):
            mode, name = funcs[addr]
            f.write(f"0x{addr:08X}\t{mode}\t{name}\n")
    print(f"[extract_map_symbols] Wrote {len(funcs)} functions to {imported_symbols_path}")

    # Write symbols/imported_data_symbols.tsv
    imported_data_symbols_path = symbols_dir / "imported_data_symbols.tsv"
    with open(imported_data_symbols_path, "w", encoding="utf-8") as f:
        f.write("# addr\tregion\tsize\tname\n")
        for addr in sorted(data_syms.keys()):
            region, size, name = data_syms[addr]
            f.write(f"0x{addr:08X}\t{region}\t0x{size:X}\t{name}\n")
    print(f"[extract_map_symbols] Wrote {len(data_syms)} data symbols to {imported_data_symbols_path}")

    # 3. Compute ROM hashes & generate game.toml
    with open(rom_path, "rb") as f:
        rom_bytes = f.read()

    rom_sha1 = hashlib.sha1(rom_bytes).hexdigest()
    rom_md5 = hashlib.md5(rom_bytes).hexdigest()
    rom_size = len(rom_bytes)
    aot_end = 0x08000000 + rom_size

    game_toml_path = root_dir / "game.toml"
    with open(game_toml_path, "w", encoding="utf-8") as f:
        f.write(f"""# Medabots: Rokusho static recompilation config
# Auto-generated by tools/extract_map_symbols.py

[game]
name = "Medabots: Rokusho"
short_name = "medabots_rokusho"

[program]
name = "Medabots: Rokusho (USA)"
id = "A9BE"
load_address = 0x08000000
size = {rom_size:#010x}
entry_pc = 0x08000000
speculative_literal_harvest = false
aot_scan_start = 0x08000000
aot_scan_end = {aot_end:#010x}
static_resume_all = true
codegen_shards = 64

[identity]
sha1 = "{rom_sha1}"
md5 = "{rom_md5}"

[bios]
path = "gbarecomp/bios/gba_bios.bin"
sha1 = "300c20df6731a33952ded8c436f7f186d25d3492"
hle = false

[rom]
path = "decomp/medabots_rokusho.gba"
sha1 = "{rom_sha1}"

[save]
type = "eeprom"
size = 8192
path = "save/rom.sav"

[runtime]
debug_port = 19872
window_title = "MedabotsRokushoRecomp"

[video]
internal_resolution = 1
screen = "frontlit"
widescreen = 0
sharp_filter = true
affine_filter = true

[audio]
shadow = false

# Startup IRQ handler copied from ROM to IWRAM
[[code_copy]]
runtime_start = 0x03001C10
source_start = 0x08000104
size = 0x00000114
name = "irq_dispatch_arm_iwram"
note = "ARM IRQ dispatch handler in IWRAM"

[[extra_func]]
addr = 0x03001C10
mode = "arm"
name = "irq_dispatch_arm_iwram_entry"
note = "ARM entry for IRQ dispatch handler in IWRAM"

# Link buffer swap copied to IWRAM
[[code_copy]]
runtime_start = 0x03005250
source_start = 0x08000218
size = 0x00000040
name = "link_buffer_swap_arm_iwram"
note = "ARM link buffer swap in IWRAM"

[[extra_func]]
addr = 0x03005250
mode = "arm"
name = "link_buffer_swap_arm_iwram_entry"
note = "ARM entry for link buffer swap in IWRAM"

# Serial multiplayer transfer handler copied to IWRAM
[[code_copy]]
runtime_start = 0x03005050
source_start = 0x08002448
size = 0x000000FC
name = "serial_multiplayer_transfer_handler_iwram"
note = "Thumb serial transfer handler in IWRAM"

[[extra_func]]
addr = 0x03005050
mode = "thumb"
name = "serial_multiplayer_transfer_handler_iwram_entry"
note = "Thumb entry for serial transfer handler in IWRAM"
""")
    print(f"[extract_map_symbols] Wrote {game_toml_path}")
    print("[extract_map_symbols] Symbol extraction complete.")

if __name__ == "__main__":
    main()
